#!/usr/bin/env bash
# Deploys one release of one project on its OVH VM, keeps the last few
# releases, and can roll back to any of them.
#
# Runs on the VM: from .github/workflows/ovh-deploy.yml (self-hosted runner),
# or by hand over SSH for status and rollback.
#
#   ovh-deploy.sh deploy               # CI: needs RELEASE_ENV and RELEASE_TAG
#   ovh-deploy.sh rollback [RELEASE]   # back to the previous (or a named) release
#   ovh-deploy.sh status
#
# Layout under DEPLOY_DIR (default /home/ubuntu/deployment/mastodon):
#   releases/<UTC time>-<tag>/mastodon.yml   copy of deploy/compose/mastodon.yml
#   releases/<UTC time>-<tag>/override.yml   optional project override
#   releases/<UTC time>-<tag>/.env           generated by deploy/bin/plan-deploy
#   current -> releases/<...>                the live release
#   deploy-history.log
#
# Deploy steps: pull -> pre-deploy migrations -> switch (up --wait) -> smoke
# test -> post-deploy migrations. If the switch or the smoke test fails, the
# previous release is started again. Database migrations are never undone.

set -Eeuo pipefail

DEPLOY_DIR="${DEPLOY_DIR:-/home/ubuntu/deployment/mastodon}"
RELEASES_DIR="$DEPLOY_DIR/releases"
CURRENT="$DEPLOY_DIR/current"
HISTORY="$DEPLOY_DIR/deploy-history.log"
KEEP_RELEASES="${KEEP_RELEASES:-5}"
WAIT_TIMEOUT="${WAIT_TIMEOUT:-600}"
SOURCE_DIR="${SOURCE_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

log() { printf '\n==> %s\n' "$*"; }
die() { printf '::error::%s\n' "$*" >&2; exit 1; }

# docker compose in a release folder. Variables that would override the
# release's .env are removed from the environment first.
dc() {
  local dir="$1"; shift
  (cd "$dir" && env -u COMPOSE_FILE -u COMPOSE_PROJECT_NAME -u WEB_IMAGE -u STREAMING_IMAGE \
    -u CREDENTIAL_DIR -u RELEASE_TAG docker compose "$@")
}

env_value() { sed -n "s/^$2=//p" "$1/.env" | tail -n 1; }

current_release() { [ -L "$CURRENT" ] && basename "$(readlink "$CURRENT")" || true; }

record() {
  printf '%s %-8s %s by=%s run=%s\n' "$(date -u +%FT%TZ)" "$1" "$2" \
    "${GITHUB_ACTOR:-$(whoami)}" "${GITHUB_RUN_ID:-manual}" >> "$HISTORY"
}

switch_to() {
  local release="$1"
  ln -sfn "releases/$release" "$CURRENT"
  dc "$CURRENT" up -d --wait --wait-timeout "$WAIT_TIMEOUT" --remove-orphans
}

smoke_test() {
  local url="${PUBLIC_URL:-}" i
  for i in 1 2 3 4 5 6; do
    if curl -fsS --max-time 10 http://127.0.0.1:3000/health >/dev/null &&
       curl -fsS --max-time 10 http://127.0.0.1:4000/api/v1/streaming/health >/dev/null &&
       { [ -z "$url" ] || curl -fsS --max-time 15 "$url/health" >/dev/null; }; then
      return 0
    fi
    sleep 10
  done
  return 1
}

restore() {
  local previous="$1" reason="$2"
  if [ -z "$previous" ]; then
    echo "::error::$reason. There is no previous release to go back to."
    return
  fi
  echo "::error::$reason. Rolling back to $previous."
  if switch_to "$previous"; then
    record rollback "$previous"
    echo "::warning::Rolled back to $previous. Database migrations from the failed release were NOT undone."
  else
    echo "::error::Rollback to $previous also failed. Check 'docker compose ps' in $CURRENT."
  fi
}

prune() {
  local keep_current keep_previous
  keep_current="$(current_release)"
  keep_previous="${1:-}"
  # Release folder names start with a UTC timestamp, so name order is time order.
  ls -1 "$RELEASES_DIR" | sort -r | tail -n "+$((KEEP_RELEASES + 1))" | while read -r old; do
    [ "$old" = "$keep_current" ] || [ "$old" = "$keep_previous" ] || rm -rf "${RELEASES_DIR:?}/$old"
  done
  docker image prune -af --filter "until=168h" >/dev/null || true
}

cmd_deploy() {
  : "${RELEASE_ENV:?RELEASE_ENV is required (generated by deploy/bin/plan-deploy)}"
  : "${RELEASE_TAG:?RELEASE_TAG is required}"
  [ -f "$SOURCE_DIR/deploy/compose/mastodon.yml" ] || die "deploy/compose/mastodon.yml not found under $SOURCE_DIR"

  local release previous new credential_dir
  release="$(date -u +%Y%m%dT%H%M%SZ)-$RELEASE_TAG"
  previous="$(current_release)"
  new="$RELEASES_DIR/$release"

  log "Preparing $release (live: ${previous:-none})"
  mkdir -p "$new"
  cp "$SOURCE_DIR/deploy/compose/mastodon.yml" "$new/mastodon.yml"
  if [ -n "${OVERRIDE_FILE:-}" ]; then
    cp "$SOURCE_DIR/$OVERRIDE_FILE" "$new/override.yml"
  fi
  printf '%s\nRELEASE_ID=%s\n' "$RELEASE_ENV" "$release" > "$new/.env"

  credential_dir="$(env_value "$new" CREDENTIAL_DIR)"
  [ -f "$credential_dir/.env.production" ] || die "$credential_dir/.env.production is missing (placed by hand, see docs/deploy/DEVOPS.md)"
  [ -f "$credential_dir/firebase/firebase.json" ] || die "$credential_dir/firebase/firebase.json is missing (placed by hand, see docs/deploy/DEVOPS.md)"
  dc "$new" config --quiet

  log "Pulling images"
  dc "$new" pull --quiet

  log "Pre-deploy migrations (SKIP_POST_DEPLOY_MIGRATIONS=true)"
  dc "$new" run --rm --no-deps -e SKIP_POST_DEPLOY_MIGRATIONS=true web bundle exec rails db:migrate

  log "Switching to $release"
  if ! switch_to "$release"; then
    restore "$previous" "Containers of $release did not become healthy"
    exit 1
  fi

  log "Smoke test"
  if ! smoke_test; then
    restore "$previous" "Smoke test of $release failed"
    exit 1
  fi

  log "Post-deploy migrations"
  if ! dc "$CURRENT" run --rm --no-deps web bundle exec rails db:migrate; then
    record deployed "$release"
    die "$release is live, but post-deploy migrations failed. Do not roll back blindly; fix forward or ask the dev team."
  fi

  record deployed "$release"
  prune "$previous"
  log "Live: $release"
  dc "$CURRENT" ps
}

cmd_rollback() {
  local target="${1:-}" live
  live="$(current_release)"
  if [ -z "$target" ]; then
    # The newest release older than the live one.
    target="$(ls -1 "$RELEASES_DIR" | sort -r | awk -v live="$live" "live == \"\" || \$0 < live" | head -n 1 || true)"
  fi
  [ -n "$target" ] && [ -d "$RELEASES_DIR/$target" ] || die "no release to roll back to (have: $(ls -1 "$RELEASES_DIR" 2>/dev/null | tr '\n' ' '))"

  log "Rolling back: ${live:-none} -> $target"
  dc "$RELEASES_DIR/$target" pull --quiet
  switch_to "$target"
  record rollback "$target"
  echo "Rolled back to $target. Database migrations were NOT undone."
  echo "Also move image_tag in deploy/projects/<project>/project.yml back, or the next deploy brings the new release again."
}

cmd_status() {
  echo "Live release: $(current_release)"
  echo "Releases (newest first):"
  ls -1 "$RELEASES_DIR" 2>/dev/null | sort -r | sed 's/^/  /'
  echo "Recent history:"
  tail -n 10 "$HISTORY" 2>/dev/null | sed 's/^/  /' || true
  [ -L "$CURRENT" ] && dc "$CURRENT" ps
}

case "${1:-}" in
  deploy) cmd_deploy ;;
  rollback) shift; cmd_rollback "${1:-}" ;;
  status) cmd_status ;;
  *) echo "usage: $0 deploy | rollback [RELEASE] | status" >&2; exit 2 ;;
esac
